//! Reviewed immutable release profiles. Version selects a profile; missing files
//! never select historical mode. Unlisted releases use the strict current path.
use super::{
    fs::{digest, read_regular},
    manifest,
};
use crate::{fail, Result};
use std::{
    collections::{BTreeMap, BTreeSet},
    path::{Path, PathBuf},
};
pub fn source_path(root: &Path, name: &str) -> PathBuf {
    if let Some(n) = name.strip_prefix("runtime/") {
        root.join("scripts").join(n)
    } else if name == "AGENTS.md" {
        root.join("docs/AGENT-GUIDE.md")
    } else if name.starts_with("docs/") || name == "LICENSE" {
        root.join(name)
    } else {
        root.join("mods/jira-peek").join(name)
    }
}
pub struct Profile {
    pub rust: bool,
    // None denotes an asset generated by verified Rust bundle staging.
    pub files: BTreeMap<String, Option<String>>,
}
impl Profile {
    pub fn inventory(&self) -> BTreeSet<String> {
        self.files.keys().cloned().collect()
    }
    pub fn installed_hash(&self, name: &str) -> Option<&str> {
        // bundle::stage replaces this source wrapper with the stable forwarding entry.
        if self.rust && name == "runtime/app-bridge.sh" {
            return None;
        }
        self.files.get(name).and_then(|s| s.as_deref())
    }
}
fn file_names(root: &Path) -> Result<BTreeSet<String>> {
    Ok(manifest::walk(root)?
        .into_iter()
        .filter(|s| !s.ends_with('/'))
        .collect())
}
pub fn validate_current(root: &Path) -> Result<()> {
    read_regular(&root.join("docs/PANEL-INTEGRATION.md"), 32 * 1024 * 1024)
        .map_err(|_| fail("unsupported_source_inventory"))?;
    let expected = manifest::inventory()
        .into_iter()
        .filter(|s| {
            !s.starts_with("runtime/")
                && !s.starts_with("docs/")
                && s != "AGENTS.md"
                && s != "LICENSE"
        })
        .collect();
    let directory = root.join("mods/jira-peek");
    let mut actual = file_names(&directory)?;
    for generated in ["gpui-kit.d.ts", "jsconfig.json"] {
        if actual.remove(generated) {
            read_regular(&directory.join(generated), 32 * 1024 * 1024)?;
        }
    }
    if actual != expected {
        return Err(fail("unsupported_source_inventory"));
    }
    Ok(())
}
pub fn historical(root: &Path, version: &str) -> Result<Option<Profile>> {
    let profiles = manifest::parse(include_bytes!("source-profiles.json"))?;
    let Some(data) = profiles.get(version) else {
        return Ok(None);
    };
    let rust = data["rust"]
        .as_bool()
        .ok_or_else(|| fail("invalid_frozen_source_profile"))?;
    let mut files = BTreeMap::new();
    for (name, hash) in data["files"]
        .as_object()
        .ok_or_else(|| fail("invalid_frozen_source_profile"))?
    {
        let hash = if hash.is_null() {
            None
        } else {
            Some(
                hash.as_str()
                    .filter(|s| manifest::hash(s))
                    .ok_or_else(|| fail("invalid_frozen_source_profile"))?
                    .to_string(),
            )
        };
        if let Some(expected) = &hash {
            if digest(&source_path(root, name))? != *expected {
                return Err(fail("historical_source_identity_mismatch"));
            }
        }
        files.insert(name.clone(), hash);
    }
    let checks = data["checks"]
        .as_object()
        .ok_or_else(|| fail("invalid_frozen_source_profile"))?;
    for (name, hash) in checks {
        if digest(&root.join(name))? != *hash {
            return Err(fail("historical_source_identity_mismatch"));
        }
    }
    if rust {
        let expected = checks
            .keys()
            .filter_map(|s| s.strip_prefix("rust-backend/src/").map(str::to_string))
            .collect();
        if file_names(&root.join("rust-backend/src"))? != expected {
            return Err(fail("historical_source_inventory_mismatch"));
        }
    } else {
        for name in [
            "rust-backend",
            ".release-runtime",
            "scripts/runtime-bundle.py",
        ] {
            match std::fs::symlink_metadata(root.join(name)) {
                Ok(_) => return Err(fail("mixed_historical_source")),
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => (),
                Err(_) => return Err(fail("unsafe_historical_source")),
            }
        }
    }
    let expected = files
        .keys()
        .filter(|s| !s.starts_with("runtime/") && *s != "AGENTS.md" && *s != "LICENSE")
        .cloned()
        .collect();
    if file_names(&root.join("mods/jira-peek"))? != expected {
        return Err(fail("historical_source_inventory_mismatch"));
    }
    Ok(Some(Profile { rust, files }))
}
